for _s in CANONICAL_STATES:
    _ALIASES[_s.lower()] = _s


def normalize_state(raw: str | None) -> str | None:
    """Normalize a state/UT name, abbreviation, or Hindi name to canonical English.

    Returns ``None`` if *raw* is empty or unrecognized.
    """
    if not raw or not isinstance(raw, str):
        return None
    cleaned = " ".join(raw.strip().lower().split())
    if not cleaned:
        return None
    return _ALIASES.get(cleaned)
